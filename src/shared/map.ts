/**
 * «Долина»: первая карта нового размера. Блоков на ней немного, и стоят они
 * островами — работать укрытием должна земля, а не расстановка. Холмы здесь
 * вдвое шире и вдвое выше, чем на «Холмах», при том же уклоне: гребень
 * перестал быть складкой, которую переезжают мимоходом, и стал направлением,
 * которое выбирают на весь бой. Объехать его — полминуты хода.
 *
 * Форма боя задана хутором в центре и четырьмя каменоломнями по углам: это
 * единственные места, где есть настоящее укрытие, и потому единственные, за
 * которые имеет смысл держаться. Между ними — гряды ниже высоты полёта: ехать
 * напрямик нельзя, стрелять поверх можно, и весь путь от угла к центру идёт
 * на виду.
 */
function buildValley(): Box[] {
  const boxes: Box[] = [];
  const add = (x: number, z: number, w: number, d: number, h: number) => {
    boxes.push({ x, z, w, d, h });
  };

  // Хутор: восемь строений вокруг площади, улицы по 12 м. Единственное место
  // карты, где дерутся вплотную.
  for (const x of [-26, 0, 26]) {
    for (const z of [-26, 0, 26]) {
      if (x === 0 && z === 0) continue;
      add(x, z, 14, 14, 4 + ((Math.abs(x) + Math.abs(z)) % 3));
    }
  }

  // Каменоломни по углам: высокое укрытие на дальних подступах, между скалами
  // есть чем проехать.
  for (const [sx, sz] of CORNERS) {
    add(sx * 92, sz * 92, 18, 18, 6);
    add(sx * 92, sz * 68, 10, 10, 4.5);
    add(sx * 68, sz * 92, 10, 10, 4.5);
    add(sx * 112, sz * 74, 8, 22, 5);
    add(sx * 74, sz * 112, 22, 8, 5);
  }

  // Гряды вокруг хутора: половинки сходятся на осях в две сплошные стенки по
  // 80 м, и въезд в центр остаётся только по диагоналям.
  for (const [sx, sz] of CORNERS) {
    add(sx * 56, sz * 20, 8, 40, LOW);
    add(sx * 20, sz * 56, 40, 8, LOW);
  }

  // Подступы: между хутором и углами иначе оставалось голое поле в сотню метров.
  for (const [sx, sz] of CORNERS) {
    add(sx * 44, sz * 76, 12, 12, 5);
    add(sx * 76, sz * 44, 12, 12, 5);
    add(sx * 62, sz * 62, 10, 10, 4);
    add(sx * 116, sz * 22, 10, 26, 4);
    add(sx * 22, sz * 116, 26, 10, 4);
    add(sx * 34, sz * 100, 14, 6, LOW);
    add(sx * 100, sz * 34, 6, 14, LOW);
  }

  // Осевые скалы: ориентиры на пустых серединах сторон.
  add(0, 118, 26, 10, 5);
  add(0, -118, 26, 10, 5);
  add(118, 0, 10, 26, 5);
  add(-118, 0, 10, 26, 5);

  return boxes;
}

/**
 * «Промзона»: вторая большая карта и полная противоположность «Долине». Рельеф
 * тут почти незаметен — пологая площадка, которую строители и так выровняли под
 * цеха, — а всю работу делает застройка.
 *
 * Комбинат разбит на кварталы 30×30 с улицами по 16 м, и кварталы двух сортов
 * вперемешку: цех — два глухих корпуса с проходом между ними, двор — ряды
 * контейнеров ниже высоты полёта. Из-за этого одна и та же улица одновременно
 * простреливается насквозь поверх дворов и перекрыта цехами, и «вижу» с
 * «достану» расходятся на каждом перекрёстке.
 *
 * Снаружи комбинат обнесён оградой с четырьмя воротами; спавны — за ней, так
 * что бой начинается с выбора ворот. По углам ограда не сходится: там ещё
 * четыре входа наискось, и держать все восемь никому не хватит танков.
 */
function buildWorks(): Box[] {
  const boxes: Box[] = [];
  const add = (x: number, z: number, w: number, d: number, h: number) => {
    boxes.push({ x, z, w, d, h });
  };

  // Градирня — единственная башня комбината, видно её с любого края карты.
  add(0, 0, 22, 22, 8);
  // Отстойники вокруг неё низкие: подойти к градирне можно только по осям.
  for (const [sx, sz] of CORNERS) add(sx * 18, sz * 18, 8, 8, LOW);

  const grid = [-92, -46, 0, 46, 92];
  for (let i = 0; i < grid.length; i++) {
    for (let j = 0; j < grid.length; j++) {
      const x = grid[i];
      const z = grid[j];
      if (x === 0 && z === 0) continue;
      if ((i + j) % 2 === 0) {
        // Цех: корпуса разной высоты, между ними проход в 10 м — сквозной, но
        // простреливаемый с обеих улиц.
        add(x, z - 10, 30, 10, 5 + ((i * 3 + j) % 3) * 0.5);
        add(x, z + 10, 30, 10, 5 + ((i + j * 3) % 3) * 0.5);
      } else {
        // Двор: два ряда контейнеров и будка, запирающая проезд с одной стороны.
        for (const dz of [-9, 9]) add(x, z + dz, 26, 5, LOW);
        add(x + 10, z, 8, 8, 4.5);
      }
    }
  }

  // Ограда: по два пролёта на сторону, ворота шириной 48 м посередине каждой.
  for (const s of [1, -1]) {
    for (const d of [-1, 1]) {
      add(d * 64, s * 122, 80, 10, 5);
      add(s * 122, d * 64, 10, 80, 5);
    }
  }

  return boxes;
}

