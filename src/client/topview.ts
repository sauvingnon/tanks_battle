/**
 * Геометрия вида сверху: ортографическая камера над танком и обратный к ней
 * пересчёт точки на экране в угол наводки.
 *
 * Это ровно та арифметика, которую по картинке не проверишь: перепутанный знак
 * даёт зеркальную карту, в которой всё работает и всё едет не туда. Поэтому она
 * живёт отдельно от рендера, без three и без DOM, и её сверяет npm run check:view.
 */

/**
 * С какой высоты смотрит камера, м. Проекция ортографическая, так что на
 * картинку высота не влияет вовсе — она задаёт только глубину отсечения.
 */
export const TOP_HEIGHT = 90;

/**
 * Во сколько метров обзора превращается одно деление зума. Зум общий с видом от
 * третьего лица (7..36), поэтому вокруг танка видно 10..54 м.
 */
export const TOP_ZOOM_SCALE = 1.5;

/**
 * Границы кадра. Радиус считается по короткой стороне экрана: тогда вокруг
 * танка видно одно и то же и в портрете, и в ландшафте, и повернуть телефон —
 * это выбор удобства, а не преимущество в обзоре.
 */
export function topFrustum(
  radius: number,
  aspect: number,
): { halfWidth: number; halfHeight: number } {
  return aspect >= 1
    ? { halfWidth: radius * aspect, halfHeight: radius }
    : { halfWidth: radius, halfHeight: radius / aspect };
}

/**
 * Угол наводки по смещению от танка в пикселях экрана.
 *
 * Камера вида сверху поставлена так (up = -Z), что вправо по экрану — это +X
 * мира, а вниз — +Z. Угол 0 в игре смотрит в +Z, а sin отвечает за X, поэтому
 * горизонталь экрана идёт первым аргументом, а вертикаль — вторым.
 */
export function aimAngle(dx: number, dy: number): number {
  return Math.atan2(dx, dy);
}

/**
 * Угол обзора для перевода метров в пиксели у частиц.
 *
 * Шейдер пыли делит размер точки на глубину — это перспектива, и у ортокамеры
 * такого деления нет. Вместо правки шейдера подбираем тот fov, при котором
 * перспектива с высоты TOP_HEIGHT дала бы на земле ровно тот же масштаб: у
 * земли совпадает точно, а пыль поднимается на метр-другой, и разница в размере
 * там — проценты.
 */
export function topParticleFov(halfHeight: number): number {
  return (Math.atan(halfHeight / TOP_HEIGHT) * 360) / Math.PI;
}
